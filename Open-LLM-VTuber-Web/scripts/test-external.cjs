const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const file = require('node:path').resolve(__dirname, '../src/renderer/src/pet/external-state.ts');
const moduleCopy = new Module(file);
moduleCopy._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, file);
const { ExternalState } = moduleCopy.exports;
const state = new ExternalState();
assert.equal(state.tick(1000), false);
state.task({ task_id:'a',status:'running',expires_at:10 });
state.task({ task_id:'b',status:'running',expires_at:12 });
assert.equal(state.tick(2000), true);
state.task({ task_id:'a',status:'completed',expires_at:10 });
assert.equal(state.tick(2000), true, 'a completed task must not release another task');
assert.equal(state.tick(12001), false, 'abandoned tasks expire');
state.setExpression('wink', 2000, 15000);
assert.equal(state.expression.name, 'wink');
assert.equal(state.tick(16000), true);
assert.equal(state.tick(17000), false);
assert.equal(state.expression, null);
state.setExpression('happy',1000,20000);
state.reset();
assert.equal(state.tick(20001),false);
assert.equal(state.tasks.size,0);
console.log('External task leases, concurrent holds, expression expiry and reconnect reset passed.');
