const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
function load(relative) {
  const file = require('node:path').resolve(__dirname, relative);
  const copy = new Module(file);
  copy.paths = module.paths;
  copy._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, file);
  return copy.exports;
}
const { ExternalState } = load('../src/renderer/src/pet/external-state.ts');
const { appendFilePaths } = load('../src/renderer/src/pet/draft.ts');
const state = new ExternalState();
assert.equal(state.tick(1000), false);
state.setExpression('wink', 2000, 1000);
assert.equal(state.tick(1100), false, 'an expression never wakes the pet');
assert.equal(state.resolveExpression(true, 1100), 'sleep', 'sleep overrides an unexpired emotion');
assert.equal(state.resolveExpression(false, 1100), 'wink', 'app-awakened pet accepts agent expressions');
assert.throws(() => state.setExpression('sleep', 1000, 1200), /application/);
state.task({ task_id:'a',status:'running',expires_at:10 }, 2000);
assert.equal(state.expression, null, 'task start replaces the prior emotion');
state.setExpression('playful', 30000, 2100);
assert.equal(state.resolveExpression(false, 2200), 'playful', 'agent expressions work during a task');
state.task({ task_id:'b',status:'running',expires_at:12 }, 2300);
state.task({ task_id:'a',status:'completed',expires_at:10 }, 2500);
assert.equal(state.tick(2500), true, 'one completed task cannot release another');
assert.equal(state.resolveExpression(false, 2600), 'neutral', 'another task remains in progress');
state.task({ task_id:'b',status:'failed',expires_at:12 }, 3000);
state.setExpression('happy', 30000, 3100);
assert.equal(state.resolveExpression(false, 3200), 'hurt', 'task outcome overrides an agent expression');
assert.equal(state.resolveExpression(true, 3200), 'sleep', 'sleep always wins');
assert.equal(state.resolveExpression(false, 6001), 'happy', 'agent expressions resume only after the task reaction');
state.reset();
state.task({ task_id:'expired',status:'running',expires_at:10 }, 5000);
state.setExpression('angry', 30000, 5000);
assert.equal(state.tick(10001), false, 'abandoned task releases its activity hold');
assert.equal(state.expression, null, 'expiry clears stale task emotion');
state.reset();
assert.equal(state.tasks.size,0);
assert.equal(state.tick(20001),false);
const file = 'C:\\work\\file with spaces.txt';
assert.equal(appendFilePaths('  keep text  ', [file, file]), '  keep text  \n' + JSON.stringify(file));
assert.equal(appendFilePaths('', []), '');
assert.equal(appendFilePaths('draft\n', [file]), 'draft\n' + JSON.stringify(file));
console.log('Application sleep/task/expression priority, expiry, concurrency and visible file paths passed.');
